import { notEmpty, isPresent, pymod } from '../helpers'
import { ParsedOptions, Frequency } from '../types'
import { YearInfo, rebuildYear } from './yearinfo'
import { MonthInfo } from './monthinfo'
import { easter } from './easter'
import { Time } from '../datetime'
import { ONE_DAY, sort, utcMs } from '../dateutil'

// =============================================================================
// Iterinfo
// =============================================================================
//
// Forked from rrule.js 2.8.0. Changes:
//  * the year masks are rebuilt only when the year changes (rrule.js tracked
//    the last year through the month info, which only exists for nth BYDAY,
//    so every other rule rebuilt them on every period);
//  * the day set of a period is a compact, reused list of the day-of-year
//    indices that pass the BY* filters (`fillDayset`), instead of a fresh
//    year-long array with nulls;
//  * BY* lookups use precomputed tables, and plain and nth BYDAY are OR-ed
//    (RFC 5545) instead of AND-ed.

/** Dense membership table for small non-negative integers. */
function table(values: number[] | null | undefined, size: number, sign = 1) {
  if (!notEmpty(values)) return null
  const t = new Uint8Array(size)
  for (let i = 0; i < values.length; i++) {
    const v = values[i] * sign
    if (v >= 0 && v < size) t[v] = 1
  }
  return t
}

export default class Iterinfo {
  public yearinfo: YearInfo
  public monthinfo: MonthInfo
  public eastermask: number[] | null

  /** Day-of-year indices of the current period that passed the filters. */
  public readonly days = new Int32Array(366 + 7)
  /** Whether the last day of the current period was filtered out. */
  public lastFiltered = false

  private _lastyear: number | null = null

  private readonly bymonthT: Uint8Array | null
  private readonly byweekdayT: Uint8Array | null
  private readonly hasNth: boolean
  private readonly bymonthdayT: Uint8Array | null
  private readonly bynmonthdayT: Uint8Array | null
  private readonly hasMonthday: boolean
  private readonly byyeardayPos: Uint8Array | null
  private readonly byyeardayNeg: Uint8Array | null
  private readonly hasWeekno: boolean
  private readonly hasEaster: boolean
  /** RFC 7529 SKIP: 0 = omit, 1 = forward, -1 = backward (when applicable). */
  private readonly skipMode: number

  constructor(private options: ParsedOptions) {
    this.bymonthT = table(options.bymonth, 13)
    this.byweekdayT = table(options.byweekday, 7)
    this.hasNth = notEmpty(options.bynweekday)
    this.bymonthdayT = table(options.bymonthday, 32)
    this.bynmonthdayT = table(options.bynmonthday, 32, -1)
    this.hasMonthday =
      notEmpty(options.bymonthday) || notEmpty(options.bynmonthday)
    this.byyeardayPos = table(options.byyearday, 367)
    this.byyeardayNeg = table(options.byyearday, 367, -1)
    this.hasWeekno = notEmpty(options.byweekno)
    this.hasEaster = options.byeaster !== null && options.byeaster !== undefined
    // SKIP only changes anything for invalid month days generated by positive
    // BYMONTHDAY values in MONTHLY/YEARLY rules. Invalid dates never pass
    // BYWEEKNO or BYYEARDAY (RFC 8984 section 4.3.3.1), so those rules keep
    // omitting them.
    this.skipMode =
      (options.freq === Frequency.MONTHLY || options.freq === Frequency.YEARLY) &&
      notEmpty(options.bymonthday) &&
      !this.hasWeekno &&
      !notEmpty(options.byyearday)
        ? options.skip === 'FORWARD'
          ? 1
          : options.skip === 'BACKWARD'
            ? -1
            : 0
        : 0
  }

  rebuild(year: number, month: number) {
    const options = this.options

    if (year !== this._lastyear) {
      this.yearinfo = rebuildYear(year, options)
    }

    if (
      this.hasNth &&
      (month !== this.lastmonth || year !== this._lastyear)
    ) {
      this.rebuildNthMask(year, month)
    }

    if (isPresent(options.byeaster)) {
      this.eastermask = easter(year, options.byeaster)
    }

    this._lastyear = year
  }

  // nth-weekday mask (rrule.js monthinfo.ts rebuildMonth), kept in one
  // reused buffer: only the indices set for the previous month are cleared.
  private readonly nwBuf = new Uint8Array(366 + 7)
  private nwSet: number[] = []

  private rebuildNthMask(year: number, month: number) {
    const options = this.options
    const { yearlen, mrange, wdaymask } = this.yearinfo
    const buf = this.nwBuf
    for (let k = 0; k < this.nwSet.length; k++) buf[this.nwSet[k]] = 0
    const set: number[] = []

    // Weekly frequency never gets here (nth weekdays only count for MONTHLY
    // and YEARLY), so cross-year periods do not matter.
    const addRange = (first: number, last: number) => {
      for (let k = 0; k < options.bynweekday.length; k++) {
        const [wday, n] = options.bynweekday[k]
        let i: number
        if (n < 0) {
          i = last + (n + 1) * 7
          i -= pymod(wdaymask[i] - wday, 7)
        } else {
          i = first + (n - 1) * 7
          i += pymod(7 - wdaymask[i] + wday, 7)
        }
        if (first <= i && i <= last) {
          buf[i] = 1
          set.push(i)
        }
      }
    }
    if (options.freq === Frequency.YEARLY) {
      if (!notEmpty(options.bymonth)) {
        addRange(0, yearlen - 1)
      } else {
        for (let j = 0; j < options.bymonth.length; j++) {
          const m = options.bymonth[j]
          addRange(mrange[m - 1], mrange[m] - 1)
        }
      }
    } else if (options.freq === Frequency.MONTHLY) {
      addRange(mrange[month - 1], mrange[month] - 1)
    }
    this.nwSet = set
    this.monthinfo = {
      lastyear: year,
      lastmonth: month,
      nwdaymask: buf as unknown as number[],
    }
  }

  get lastyear() {
    return this._lastyear
  }

  get lastmonth() {
    return this.monthinfo ? this.monthinfo.lastmonth : null
  }

  get yearlen() {
    return this.yearinfo.yearlen
  }

  get yearordinal() {
    return this.yearinfo.yearordinal
  }

  get mrange() {
    return this.yearinfo.mrange
  }

  get wdaymask() {
    return this.yearinfo.wdaymask
  }

  get mmask() {
    return this.yearinfo.mmask
  }

  get wnomask() {
    return this.yearinfo.wnomask
  }

  get nwdaymask() {
    return this.monthinfo ? this.monthinfo.nwdaymask : []
  }

  get nextyearlen() {
    return this.yearinfo.nextyearlen
  }

  get mdaymask() {
    return this.yearinfo.mdaymask
  }

  get nmdaymask() {
    return this.yearinfo.nmdaymask
  }

  /**
   * Computes the day set of the period starting at (year, month, day),
   * removes the filtered days and stores the remaining ones in `days`.
   * Returns how many there are.
   */
  fillDayset(freq: Frequency, year: number, month: number, day: number) {
    let start: number
    let end: number
    switch (freq) {
      case Frequency.YEARLY:
        start = 0
        end = this.yearlen
        break
      case Frequency.MONTHLY:
        start = this.mrange[month - 1]
        end = this.mrange[month]
        break
      case Frequency.WEEKLY: {
        // Cross-year weeks: indices may run up to yearlen + 6.
        const wdaymask = this.wdaymask
        const wkst = this.options.wkst
        let i = Math.floor(utcMs(year, month - 1, day) / ONE_DAY) - this.yearordinal
        start = i
        for (let j = 0; j < 7; j++) {
          ++i
          if (wdaymask[i] === wkst) break
        }
        end = i
        break
      }
      default:
        start = Math.floor(utcMs(year, month - 1, day) / ONE_DAY) - this.yearordinal
        end = start + 1
    }

    const days = this.days
    let n = 0
    let filtered = false
    for (let d = start; d < end; d++) {
      filtered = this.isFiltered(d)
      if (!filtered) days[n++] = d
    }
    this.lastFiltered = filtered
    if (this.skipMode !== 0) n = this.addSkipped(freq, month, n)
    return n
  }

  /** Whether SKIP=FORWARD/BACKWARD is in effect (see addSkipped). */
  get skips() {
    return this.skipMode !== 0
  }

  /**
   * RFC 7529 / RFC 8984 SKIP: a BYMONTHDAY value beyond the end of a month
   * (February 30) is an invalid date that is moved to the first day of the
   * next month (FORWARD) or the last day of the month (BACKWARD), then
   * checked against BYDAY, and de-duplicated within the period.
   */
  private addSkipped(freq: Frequency, month: number, n: number) {
    const y = this.yearinfo
    const days = this.days
    const first = freq === Frequency.MONTHLY ? month : 1
    const last = freq === Frequency.MONTHLY ? month : 12
    // A date moved FORWARD lands in the next month. Where nth weekdays count
    // within a month (MONTHLY, YEARLY with BYMONTH), it is checked against
    // that month's, not the source month's (RFC 7529 section 4.1: BYDAY
    // applies to the adjusted date). YEARLY nth weekdays count within the
    // year, which the move never leaves (December has 31 days).
    const crossMonth =
      this.skipMode > 0 && (freq === Frequency.MONTHLY || this.bymonthT !== null)
    let added = false
    for (let m = first; m <= last; m++) {
      if (this.bymonthT !== null && this.bymonthT[m] !== 1) continue
      const start = y.mrange[m - 1]
      const end = y.mrange[m]
      const mlen = end - start
      let overflows = false
      const bymonthday = this.options.bymonthday
      for (let k = 0; k < bymonthday.length; k++) {
        if (bymonthday[k] > mlen) overflows = true
      }
      if (!overflows) continue
      const idx = this.skipMode < 0 ? end - 1 : end
      if (!this.matchesByday(idx, crossMonth)) continue
      let dup = false
      for (let j = 0; j < n; j++) {
        if (days[j] === idx) dup = true
      }
      if (!dup) {
        days[n++] = idx
        added = true
      }
    }
    if (added) days.subarray(0, n).sort()
    return n
  }

  /**
   * BYDAY (plain or nth) and BYEASTER checks of one day. With `ownMonth`, nth
   * weekdays count within the day's own month rather than the period's mask.
   */
  private matchesByday(d: number, ownMonth: boolean) {
    if (this.hasEaster) return false
    const byweekdayT = this.byweekdayT
    if (byweekdayT === null && !this.hasNth) return true
    if (byweekdayT !== null && byweekdayT[this.yearinfo.wdaymask[d]] === 1) return true
    if (!this.hasNth) return false
    if (!ownMonth) return this.monthinfo ? this.monthinfo.nwdaymask[d] === 1 : false
    const { mmask, mrange, wdaymask } = this.yearinfo
    const m = mmask[d]
    const first = mrange[m - 1]
    const last = mrange[m] - 1
    const nth = this.options.bynweekday
    for (let k = 0; k < nth.length; k++) {
      const [wday, n] = nth[k]
      let i: number
      if (n < 0) {
        i = last + (n + 1) * 7
        i -= pymod(wdaymask[i] - wday, 7)
      } else {
        i = first + (n - 1) * 7
        i += pymod(7 - wdaymask[i] + wday, 7)
      }
      if (i === d) return true
    }
    return false
  }

  isFiltered(d: number): boolean {
    const y = this.yearinfo
    if (this.bymonthT !== null && this.bymonthT[y.mmask[d]] !== 1) return true
    if (this.hasWeekno && !y.wnomask[d]) return true

    // RFC 5545: a day matches BYDAY if it matches a plain weekday OR an nth
    // weekday. rrule.js (and python-dateutil) required both.
    const byweekdayT = this.byweekdayT
    const nwdaymask = this.hasNth && this.monthinfo ? this.monthinfo.nwdaymask : null
    if (
      (byweekdayT !== null || (nwdaymask !== null && nwdaymask.length > 0)) &&
      !(byweekdayT !== null && byweekdayT[y.wdaymask[d]] === 1) &&
      !(nwdaymask !== null && nwdaymask[d] === 1)
    ) {
      return true
    }

    if (this.hasEaster && this.eastermask.indexOf(d) === -1) return true

    if (
      this.hasMonthday &&
      !(this.bymonthdayT !== null && this.bymonthdayT[y.mdaymask[d]] === 1) &&
      !(this.bynmonthdayT !== null && this.bynmonthdayT[-y.nmdaymask[d]] === 1)
    ) {
      return true
    }

    const pos = this.byyeardayPos
    if (pos !== null || this.byyeardayNeg !== null) {
      const neg = this.byyeardayNeg
      const yearlen = y.yearlen
      // Positive values v match day v - 1; negative v match yearlen + v.
      let p: number
      let q: number
      if (d < yearlen) {
        p = d + 1
        q = yearlen - d
      } else {
        p = d + 1 - yearlen
        q = y.nextyearlen - (d - yearlen)
      }
      const hit =
        (pos !== null && p < 367 && pos[p] === 1) ||
        (neg !== null && q < 367 && neg[q] === 1)
      if (!hit) return true
    }

    return false
  }

  htimeset(hour: number, _: number, second: number, millisecond: number) {
    let set: Time[] = []
    this.options.byminute.forEach((minute) => {
      set = set.concat(this.mtimeset(hour, minute, second, millisecond))
    })
    sort(set)
    return set
  }

  mtimeset(hour: number, minute: number, _: number, millisecond: number) {
    const set = this.options.bysecond.map(
      (second) => new Time(hour, minute, second, millisecond)
    )
    sort(set)
    return set
  }

  stimeset(hour: number, minute: number, second: number, millisecond: number) {
    return [new Time(hour, minute, second, millisecond)]
  }

  gettimeset(
    freq: Frequency
  ): (h: number, m: number, s: number, ms: number) => Time[] {
    switch (freq) {
      case Frequency.HOURLY:
        return this.htimeset.bind(this)
      case Frequency.MINUTELY:
        return this.mtimeset.bind(this)
      default:
        return this.stimeset.bind(this)
    }
  }
}
